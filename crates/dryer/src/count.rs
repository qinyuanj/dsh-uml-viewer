//! `--min-lines` and `--min-nodes` parsing with pinned dryer's semantics.
//!
//! The original parses both options with CPython `int()` (`_count` in
//! `cli.py`): it trims Unicode White_Space from both ends, accepts one
//! optional sign and decimal digits from any script (category Nd) with single
//! underscores between digits, refuses anything else as an integer error, and
//! enforces the interpreter's format-`int` limit of 4300 digits. A negative
//! value is its own error. The value is only ever compared with line and node
//! counts, so an accepted count beyond `usize::MAX` saturates.

use quality_core::number::decimal_digit as digit_of;

/// CPython 3.12's default `sys.get_int_max_str_digits()`.
pub(crate) const MAX_DECIMAL_DIGITS: usize = 4300;

#[derive(Debug, PartialEq, Eq)]
pub(crate) enum CountError {
    /// `int()` raised: the spelling is not an integer.
    NotInteger,
    /// `int()` accepted a negative value; the option requires a count.
    Negative,
}

/// The code points `int()` trims: CPython's White_Space table, which is
/// narrower than `str.isspace()` (it keeps U+001C..U+001F).
pub(crate) fn is_space(char: char) -> bool {
    char.is_whitespace()
}

pub(crate) fn parse(value: &str) -> Result<usize, CountError> {
    let text = value.trim_matches(is_space);
    let (negative, digits) = match text.as_bytes().first() {
        Some(b'+') => (false, &text[1..]),
        Some(b'-') => (true, &text[1..]),
        _ => (false, text),
    };
    let mut total: usize = 0;
    let mut count: usize = 0;
    let mut previous_digit = false;
    for char in digits.chars() {
        if let Some(digit) = digit_of(char) {
            count += 1;
            if count > MAX_DECIMAL_DIGITS {
                return Err(CountError::NotInteger);
            }
            total = total.saturating_mul(10).saturating_add(digit as usize);
            previous_digit = true;
        } else if char == '_' && previous_digit {
            previous_digit = false;
        } else {
            return Err(CountError::NotInteger);
        }
    }
    if !previous_digit {
        return Err(CountError::NotInteger);
    }
    if negative && total != 0 {
        return Err(CountError::Negative);
    }
    Ok(total)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Fixtures are generated by `scripts/dry_count_oracle.py` from the pinned
    /// CPython `int()`, so the port cannot agree with itself.
    fn decode(encoded: &str) -> String {
        let mut text = String::new();
        let mut chars = encoded.chars();
        while let Some(char) = chars.next() {
            if char != '\\' {
                text.push(char);
                continue;
            }
            match chars.next().unwrap() {
                '\\' => text.push('\\'),
                'u' => {
                    assert_eq!(Some('{'), chars.next());
                    let mut hex = String::new();
                    loop {
                        match chars.next().expect("unterminated \\u{") {
                            '}' => break,
                            digit => hex.push(digit),
                        }
                    }
                    let code = u32::from_str_radix(&hex, 16).unwrap();
                    text.push(char::from_u32(code).unwrap());
                }
                other => panic!("unknown escape \\{other}"),
            }
        }
        text
    }

    fn lines(fixture: &'static str) -> impl Iterator<Item = Vec<&'static str>> {
        fixture
            .lines()
            .filter(|line| !line.is_empty() && !line.starts_with('#'))
            .map(|line| line.split('\t').collect())
    }

    #[test]
    fn every_python_int_spelling_parses_the_same_way() {
        let mut cases = 0;
        for fields in lines(include_str!("../../../fixtures/dry/count/cases.tsv")) {
            let [kind, value, expected] = fields[..] else {
                panic!("unexpected case line {fields:?}");
            };
            assert_eq!(kind, "count");
            let value = decode(value);
            let actual = parse(&value);
            match expected {
                "integer" => assert_eq!(Err(CountError::NotInteger), actual, "{value:?}"),
                "negative" => assert_eq!(Err(CountError::Negative), actual, "{value:?}"),
                "ok" => assert!(parse(&value).is_ok(), "{value:?}"),
                number => {
                    let number = number
                        .strip_prefix("ok:")
                        .expect("accepted case carries its value");
                    assert_eq!(
                        Ok(number.parse().unwrap()),
                        actual,
                        "{value:?} accepted with a different value"
                    );
                }
            }
            cases += 1;
        }
        assert!(cases > 40, "only {cases} oracle cases");
    }

    #[test]
    fn the_decimal_digit_limit_is_the_pinned_interpreters() {
        let fixture = include_str!("../../../fixtures/dry/count/limits.tsv");
        let limit: usize = fixture
            .lines()
            .find_map(|line| line.strip_prefix("max-decimal-digits\t"))
            .expect("limited fixture")
            .parse()
            .unwrap();
        assert_eq!(limit, MAX_DECIMAL_DIGITS);
        assert!(parse(&"1".repeat(limit)).is_ok());
        assert_eq!(Err(CountError::NotInteger), parse(&"1".repeat(limit + 1)));
        assert!(parse(&("1_".repeat(limit - 1) + "1")).is_ok());
    }

    #[test]
    fn the_trimmed_whitespace_is_the_interpreters_own_set() {
        let fixture = include_str!("../../../fixtures/dry/count/whitespace.tsv");
        let mut spaces = Vec::new();
        for line in fixture.lines().filter(|line| !line.starts_with('#')) {
            let code = u32::from_str_radix(line.trim().trim_start_matches("0x"), 16).unwrap();
            spaces.push(char::from_u32(code).unwrap());
        }
        // The White_Space property: 25 code points. Python's `str.isspace()`
        // has four more (U+001C..U+001F) that `int()` does not trim.
        assert_eq!(25, spaces.len());
        for code in 0..=0x10FFFF {
            if let Some(char) = char::from_u32(code) {
                assert_eq!(
                    spaces.contains(&char),
                    is_space(char),
                    "trimming U+{code:04X}"
                );
            }
        }
    }

    #[test]
    fn the_generated_digit_runs_are_ten_wide_and_ordered() {
        let fixture = include_str!("../../../fixtures/dry/count/limits.tsv");
        let runs: usize = fixture
            .lines()
            .find_map(|line| line.strip_prefix("decimal-runs\t"))
            .expect("runs fixture")
            .parse()
            .unwrap();
        assert_eq!(runs, quality_core::digits::DECIMAL_DIGIT_RUNS.len());
        let mut previous = None;
        for (start, end) in quality_core::digits::DECIMAL_DIGIT_RUNS {
            assert_eq!(9, end - start, "run {start:04X}-{end:04X}");
            assert!(previous.is_none_or(|last| last < *start));
            for digit in 0..10 {
                let char = char::from_u32(start + digit).unwrap();
                assert_eq!(Some(digit), digit_of(char), "U+{:04X}", start + digit);
            }
            previous = Some(*end);
        }
    }
}
