"""Capture pinned crapper's platform refusals; never synthesize expected text.

python -I scripts/crap_platform_oracle.py <crapper-checkout> [--check]
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
FIXTURES = REPO / "fixtures" / "crap" / "platform"
PIN = "4068857bc44e6383cf4a5e4d0b5c1111b49ce0b4"
REFUSALS = [
    ("linux", None),
    ("win32", None),
    ("win32", 19045),
    ("win32", 22000),
    ("win32", 26220),
    ("win32", 10240),
    ("win32", 17763),
    ("win32", 19041),
    ("win32", 19044),
]


def original(checkout: Path) -> None:
    result = subprocess.run(
        ["git", "-C", str(checkout), "rev-parse", "HEAD"],
        capture_output=True, text=True, check=True,
    )
    if result.stdout.strip() != PIN:
        raise SystemExit(f"crapper: expected {PIN}, got {result.stdout.strip()}")
    result = subprocess.run(
        ["git", "-C", str(checkout), "-c", "core.autocrlf=true",
         "status", "--porcelain", "--", "src", "pyproject.toml"],
        capture_output=True, text=True, check=True,
    )
    if result.stdout:
        raise SystemExit("crapper: source checkout must be clean")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("crapper", type=Path)
    parser.add_argument("--check", action="store_true", help="compare without writing")
    options = parser.parse_args()
    crapper = options.crapper.resolve()
    original(crapper)
    sys.path.insert(0, str(crapper / "src"))
    from crapper.platform import MINIMUM_WINDOWS_BUILD, refusal

    def shown(answer: str | None) -> str:
        return "none" if answer is None else answer

    lines = [
        "# Generated by scripts/crap_platform_oracle.py from pinned crapper; do not edit.",
        f"# crapper\t{PIN}",
        f"# interpreter\t{sys.version.split()[0]} ({sys.platform})",
        f"min-windows-build\t{MINIMUM_WINDOWS_BUILD}",
    ]
    lines += [
        f"refusal\t{host}\t{build if build is not None else 'none'}\t{shown(refusal(host, build))}"
        for host, build in REFUSALS
    ]
    expected = ("\n".join(lines) + "\n").encode("utf-8")
    path = FIXTURES / "cases.tsv"
    if options.check:
        actual = path.read_bytes() if path.is_file() else None
        if actual != expected:
            raise SystemExit(f"Oracle differences:\n{path.relative_to(REPO)}")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(expected)
        print(f"{path.relative_to(REPO)}: {len(expected)} bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
