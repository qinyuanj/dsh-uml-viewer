"""Capture the pinned crapper's platform decisions; never synthesize expected text.

crapper has no platform refusal (qinyuanj/crapper#18): the operating system
alone decides, on any Windows build. The decision left to reproduce is its WSL2
/mnt warning, which the Rust port must match byte for byte. The expected lines
come from calling the pinned original, so a wording change in the port cannot
pass by agreeing with itself.

Roots are PurePosixPaths: the port renders a root with
quality_core::paths::posix, and the original only ever meets a /mnt root on the
POSIX host where this warning fires, so the fixture must not embed the oracle
host's path separator.

python -I scripts/crap_platform_oracle.py <crapper-checkout> [--check]
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path, PurePosixPath

REPO = Path(__file__).resolve().parents[1]
FIXTURES = REPO / "fixtures" / "crap" / "platform"
PIN = "91cd10c311b02366ed35874ed3d9a9bebcbe1217"
WARNINGS = [
    ("linux", "/mnt/c/proj"),
    ("linux", "/mnt/d/dev/project"),
    ("linux", "/mnt"),
    ("linux", "/home/me/proj"),
    ("win32", "C:/Users/me/proj"),
    ("win32", "/mnt/c/proj"),
]


def original(checkout: Path) -> None:
    result = subprocess.run(
        ["git", "-C", str(checkout), "rev-parse", "HEAD"],
        capture_output=True, text=True, check=True,
    )
    if result.stdout.strip() != PIN:
        raise SystemExit(f"crapper: expected {PIN}, got {result.stdout.strip()}")
    result = subprocess.run(
        ["git", "-C", str(checkout), "-c", "core.autocrlf=true",
         "status", "--porcelain", "--", "src", "pyproject.toml"],
        capture_output=True, text=True, check=True,
    )
    if result.stdout:
        raise SystemExit("crapper: source checkout must be clean")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("crapper", type=Path)
    parser.add_argument("--check", action="store_true", help="compare without writing")
    options = parser.parse_args()
    crapper = options.crapper.resolve()
    original(crapper)
    sys.path.insert(0, str(crapper / "src"))
    from crapper import platform as module
    from crapper.cli import platform_warning

    # The gate is gone for good (crapper#18); one coming back would need fixture
    # rows this oracle no longer knows how to write.
    for gone in ("refusal", "windows_build", "MINIMUM_WINDOWS_BUILD"):
        if hasattr(module, gone):
            raise SystemExit(f"crapper.platform has {gone} again; add its cases here")

    def shown(answer: str | None) -> str:
        return "none" if answer is None else answer

    lines = [
        "# Generated by scripts/crap_platform_oracle.py from pinned crapper; do not edit.",
        f"# crapper\t{PIN}",
        f"# interpreter\t{sys.version.split()[0]} ({sys.platform})",
    ]
    lines += [
        f"warning\t{host}\t{root}\t{shown(platform_warning(host, PurePosixPath(root)))}"
        for host, root in WARNINGS
    ]
    expected = ("\n".join(lines) + "\n").encode("utf-8")
    path = FIXTURES / "cases.tsv"
    if options.check:
        actual = path.read_bytes() if path.is_file() else None
        if actual != expected:
            raise SystemExit(f"Oracle differences:\n{path.relative_to(REPO)}")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(expected)
        print(f"{path.relative_to(REPO)}: {len(expected)} bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
