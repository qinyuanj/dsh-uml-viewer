"""Capture CPython `int()` acceptance for the dryer count options; never synthesize.

The Rust port parses `--min-lines` and `--min-nodes` with CPython `int()`
semantics (pinned dryer `cli.py` `_count`), so every accepted or rejected
spelling in these fixtures comes from running the real interpreter, not from
reading the Rust parser. Python ``--check`` compares all four artifacts
without writing.

python -I scripts/dry_count_oracle.py [--check]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
FIXTURES = REPO / "fixtures" / "dry" / "count"
DIGITS = REPO / "crates" / "dryer" / "src" / "digits.rs"
PROVENANCE = "Generated by scripts/dry_count_oracle.py from the running CPython; do not edit."


def encode(text: str) -> str:
    """One line, no tabs: escape everything outside printable ASCII."""

    out = []
    for char in text:
        code = ord(char)
        if char == "\\":
            out.append("\\\\")
        elif 0x20 <= code < 0x7F:
            out.append(char)
        else:
            out.append(f"\\u{{{code:X}}}")
    return "".join(out)


def decimal_runs() -> list[tuple[int, int]]:
    """The Nd code points `int()` reads, as ten-wide runs of 0..=9."""

    runs: list[list[int]] = []
    for code in range(0x110000):
        try:
            value = int(chr(code))
        except ValueError:
            continue
        if runs and code == runs[-1][1] + 1 and value == code - runs[-1][0]:
            runs[-1][1] = code
        else:
            runs.append([code, code])
    for start, end in runs:
        if end - start != 9:
            raise SystemExit(f"unexpected digit run {start:04X}-{end:04X}")
    return [(start, end) for start, end in runs]


def whitespace() -> list[int]:
    """Code points `int()` strips from both ends.

    CPython converts the string with its White_Space table, which is narrower
    than `str.isspace()`: it does not strip U+001C..U+001F. Probe the real
    conversion rather than assume either set.
    """

    spaces = []
    for code in range(0x110000):
        char = chr(code)
        try:
            leading = int(char + "5")
            trailing = int("5" + char)
        except ValueError:
            continue
        # Both ends strip it, and a sign or digit fails one of the probes.
        if leading == 5 and trailing == 5:
            spaces.append(code)
    return spaces


def probes(limit: int) -> list[str]:
    return [
        # Accepted spellings, including Python's own whitespace and signs.
        "0",
        "4",
        "10",
        "1_0",
        " 1 ",
        "\t1\n",
        " +1_0",
        " -0",
        "+0",
        "00012",
        "\u00a012\u3000",
        "\x1c5\x1f",
        "\u0661\u0662",
        "\u0661_\u0662",
        "\u0661\u0662\u0663\u0664\u0665\u0666\u0667\u0668\u0669\u0660",
        "9223372036854775808",
        "18446744073709551616",
        "1" + "0" * 100,
        "00_0",
        "1" * limit,
        "0" * limit,
        "1_" * (limit - 1) + "1",
        # Rejected spellings Python's int() refuses.
        "",
        " ",
        "1.0",
        "0x10",
        "1e3",
        "nan",
        "inf",
        "1 0",
        "1__0",
        "_1",
        "1_",
        "1_0_",
        "+",
        "-",
        "1.",
        "1,0",
        "\u2163",
        "\uff0b5",
        "1" * (limit + 1),
        "0" * (limit + 1),
        # int() itself accepts these; _count refuses the negative value.
        "-5",
        " -5",
        "-00",
        "-1_0",
        "-" + "1" * limit,
        "-" + "1" * (limit + 1),
    ]


def case_lines() -> list[str]:
    limit = sys.get_int_max_str_digits()
    lines = []
    for probe in probes(limit):
        try:
            value = int(probe)
        except ValueError:
            lines.append(f"count\t{encode(probe)}\tinteger")
            continue
        if value < 0:
            lines.append(f"count\t{encode(probe)}\tnegative")
        elif value > 2**64 - 1:
            # Accepted arbitrary precision; the port only compares counts, so
            # expected output is "accepted" without a representable value.
            lines.append(f"count\t{encode(probe)}\tok")
        else:
            lines.append(f"count\t{encode(probe)}\tok:{value}")
    return lines


def artifacts() -> dict[Path, bytes]:
    limit = sys.get_int_max_str_digits()
    runs = decimal_runs()
    spaces = whitespace()
    digits = [
        "//! Decimal digit code points CPython `int()` accepts (Unicode category Nd).",
        "//!",
        f"//! {PROVENANCE}",
        "//!",
        "//! Each run is ten consecutive code points whose value is 0..=9, so the",
        "//! digit is `code - start`.",
        "",
        "pub(crate) const DECIMAL_DIGIT_RUNS: &[(u32, u32)] = &[",
    ]
    digits += [f"    (0x{start:04X}, 0x{end:04X})," for start, end in runs]
    digits += ["];", ""]
    return {
        DIGITS: "\n".join(digits).encode("utf-8"),
        FIXTURES / "cases.tsv": "\n".join(
            [
                f"# {PROVENANCE}",
                f"# interpreter\t{sys.version.split()[0]} ({sys.platform})",
                f"# max-decimal-digits\t{limit}",
                *case_lines(),
                "",
            ]
        ).encode("utf-8"),
        FIXTURES / "whitespace.tsv": "\n".join(
            [
                f"# {PROVENANCE}",
                "# Code points int() strips from both ends; CPython White_Space.",
                *[f"0x{code:04X}" for code in spaces],
                "",
            ]
        ).encode("utf-8"),
        FIXTURES / "limits.tsv": "\n".join(
            [
                f"# {PROVENANCE}",
                f"max-decimal-digits\t{limit}",
                f"decimal-runs\t{len(runs)}",
                f"whitespace-code-points\t{len(spaces)}",
                f"interpreter\t{sys.version}",
                "",
            ]
        ).encode("utf-8"),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="compare without writing")
    options = parser.parse_args()
    files = artifacts()
    mismatches = []
    for path, expected in files.items():
        if options.check:
            actual = path.read_bytes() if path.is_file() else None
            if actual != expected:
                mismatches.append(str(path.relative_to(REPO)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(expected)
            print(f"{path.relative_to(REPO)}: {len(expected)} bytes")
    if mismatches:
        raise SystemExit("Oracle differences:\n" + "\n".join(mismatches))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
