"""Capture the pinned dryer platform layer's answers; never synthesize.

dryer.platform.platform_warning is the original decision the Rust port must
reproduce byte for byte. The expected lines below come from calling the pinned
source, so a wording change in the port cannot pass by agreeing with itself.

dryer decides on the OS alone (qinyuanj/dryer#5): Linux, macOS and native
Windows run on any Windows build, and it refuses no OS of its own, so the
fixture pins the warning and nothing else. The oracle fails if a refusal
reappears in the pinned module, because then the fixture would need rows for it.

Roots are PurePosixPaths: the port renders a root with
quality_core::paths::posix, and the original only ever meets a /mnt root on the
POSIX host where this warning fires, so the fixture must not embed the oracle
host's path separator.

python -I scripts/dry_platform_oracle.py <dryer-checkout> [--check]
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path, PurePosixPath

REPO = Path(__file__).resolve().parents[1]
FIXTURES = REPO / "fixtures" / "dry" / "platform"
PIN = "d452700d1612b98936598b23bacc90a52a7e338b"
PROVENANCE = "Generated by scripts/dry_platform_oracle.py from pinned dryer; do not edit."

# The roots platform_warning looks at, on the hosts it looks at them.
WARNINGS = [
    ("linux", "/mnt/c/proj"),
    ("linux", "/mnt/d/dev/project"),
    ("linux", "/mnt"),
    ("linux", "/home/me/proj"),
    ("win32", "C:/Users/me/proj"),
    ("win32", "/mnt/c/proj"),
]


def original(checkout: Path) -> None:
    result = subprocess.run(
        ["git", "-C", str(checkout), "rev-parse", "HEAD"],
        capture_output=True, text=True, check=True,
    )
    if result.stdout.strip() != PIN:
        raise SystemExit(f"dryer: expected {PIN}, got {result.stdout.strip()}")
    # A Windows checkout with core.autocrlf=true has CRLF worktree files; WSL
    # git then reports every source file modified. Normalize for the check.
    result = subprocess.run(
        ["git", "-C", str(checkout), "-c", "core.autocrlf=true",
         "status", "--porcelain", "--", "src", "pyproject.toml"],
        capture_output=True, text=True, check=True,
    )
    if result.stdout:
        raise SystemExit("dryer: source checkout must be clean")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("dryer", type=Path)
    parser.add_argument("--check", action="store_true", help="compare without writing")
    options = parser.parse_args()
    dryer = options.dryer.resolve()
    original(dryer)
    sys.path.insert(0, str(dryer / "src"))
    from dryer import platform as module
    from dryer.platform import platform_warning

    # The gate is gone for good (dryer#5); a refusal coming back would need
    # fixture rows this oracle no longer knows how to write.
    if hasattr(module, "platform_refusal"):
        raise SystemExit("dryer.platform refuses an OS again; add its cases here")
    if hasattr(module, "MIN_WINDOWS_BUILD"):
        raise SystemExit("dryer.platform has a Windows build floor again")

    def shown(answer: str | None) -> str:
        return "none" if answer is None else answer

    lines = [
        f"# {PROVENANCE}",
        f"# dryer\t{PIN}",
        f"# interpreter\t{sys.version.split()[0]} ({sys.platform})",
    ]
    lines += [
        f"warning\t{host}\t{root}\t{shown(platform_warning(host, PurePosixPath(root)))}"
        for host, root in WARNINGS
    ]
    expected = ("\n".join(lines) + "\n").encode("utf-8")
    path = FIXTURES / "cases.tsv"
    if options.check:
        actual = path.read_bytes() if path.is_file() else None
        if actual != expected:
            raise SystemExit(f"Oracle differences:\n{path.relative_to(REPO)}")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(expected)
        print(f"{path.relative_to(REPO)}: {len(expected)} bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
