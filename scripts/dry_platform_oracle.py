"""Capture the pinned dryer platform layer's answers; never synthesize.

`dryer.platform.platform_refusal` and `platform_warning` are the original
decisions the Rust port must reproduce byte for byte. The expected lines below
come from importing the pinned source, so a wording or boundary change in the
port cannot pass by agreeing with itself.

Run it where the warning path is a POSIX path (WSL2/Linux), because the
original formats the *host* Path object:

python -I scripts/dry_platform_oracle.py <dryer-checkout> [--check]
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
FIXTURES = REPO / "fixtures" / "dry" / "platform"
PIN = "b3f72ad9681a6574c5714d3c54d50e2ea3eff91a"
PROVENANCE = "Generated by scripts/dry_platform_oracle.py from pinned dryer; do not edit."

# Each row is one host the pinned tests declare, plus the boundaries around the
# minimum build and the roots platform_warning looks at.
REFUSALS = [
    ("linux", None),
    ("win32", 19045),
    ("win32", 22000),
    ("win32", 26220),
    ("win32", 10240),
    ("win32", 17763),
    ("win32", 19041),
    ("win32", 19044),
]
WARNINGS = [
    ("linux", "/mnt/c/proj"),
    ("linux", "/mnt/d/dev/project"),
    ("linux", "/mnt"),
    ("linux", "/home/me/proj"),
    ("win32", "C:/Users/me/proj"),
    ("win32", "/mnt/c/proj"),
]


def original(checkout: Path) -> None:
    result = subprocess.run(
        ["git", "-C", str(checkout), "rev-parse", "HEAD"],
        capture_output=True, text=True, check=True,
    )
    if result.stdout.strip() != PIN:
        raise SystemExit(f"dryer: expected {PIN}, got {result.stdout.strip()}")
    # A Windows checkout with core.autocrlf=true has CRLF worktree files; WSL
    # git then reports every source file modified. Normalize for the check.
    result = subprocess.run(
        ["git", "-C", str(checkout), "-c", "core.autocrlf=true",
         "status", "--porcelain", "--", "src", "pyproject.toml"],
        capture_output=True, text=True, check=True,
    )
    if result.stdout:
        raise SystemExit("dryer: source checkout must be clean")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("dryer", type=Path)
    parser.add_argument("--check", action="store_true", help="compare without writing")
    options = parser.parse_args()
    dryer = options.dryer.resolve()
    original(dryer)
    sys.path.insert(0, str(dryer / "src"))
    from dryer.platform import MIN_WINDOWS_BUILD, platform_refusal, platform_warning

    def shown(answer: str | None) -> str:
        return "none" if answer is None else answer

    lines = [
        f"# {PROVENANCE}",
        f"# dryer\t{PIN}",
        f"# interpreter\t{sys.version.split()[0]} ({sys.platform})",
        f"min-windows-build\t{MIN_WINDOWS_BUILD}",
    ]
    lines += [
        f"refusal\t{host}\t{build if build is not None else 'none'}\t{shown(platform_refusal(host, build))}"
        for host, build in REFUSALS
    ]
    lines += [
        f"warning\t{host}\t{root}\t{shown(platform_warning(host, Path(root)))}"
        for host, root in WARNINGS
    ]
    expected = ("\n".join(lines) + "\n").encode("utf-8")
    path = FIXTURES / "cases.tsv"
    if options.check:
        actual = path.read_bytes() if path.is_file() else None
        if actual != expected:
            raise SystemExit(f"Oracle differences:\n{path.relative_to(REPO)}")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(expected)
        print(f"{path.relative_to(REPO)}: {len(expected)} bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
