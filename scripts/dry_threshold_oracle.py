def encode(text: str) -> str:
    """One line, no tabs: escape everything outside printable ASCII."""

    out = []
    for char in text:
        code = ord(char)
        if char == "\\":
            out.append("\\\\")
        elif 0x20 <= code < 0x7F:
            out.append(char)
        else:
            out.append(f"\\u{{{code:X}}}")
    return "".join(out)


def original(checkout: Path, name: str) -> None:
    result = subprocess.run(
        ["git", "-C", str(checkout), "rev-parse", "HEAD"],
        capture_output=True, text=True, check=True,
    )
    if result.stdout.strip() != PINS[name]:
        raise SystemExit(f"{name}: expected {PINS[name]}, got {result.stdout.strip()}")
    result = subprocess.run(
        ["git", "-C", str(checkout), "-c", "core.autocrlf=true",
         "status", "--porcelain", "--", "src", "pyproject.toml"],
        capture_output=True, text=True, check=True,
    )
    if result.stdout:
        raise SystemExit(f"{name}: source checkout must be clean")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("dryer", type=Path)
    parser.add_argument("crapper", type=Path)
    parser.add_argument("--check", action="store_true", help="compare without writing")
    options = parser.parse_args()
    dryer, crapper = options.dryer.resolve(), options.crapper.resolve()
    original(dryer, "dryer")
    original(crapper, "crapper")
    sys.path[:0] = [str(dryer / "src"), str(crapper / "src")]
    from crapper.cli import _threshold
    from dryer.cli import _number

    def answer(convert, probe: str) -> str:
        try:
            return f"ok:{convert(probe)!r}"
        except ValueError as exc:
            return f"error:{exc}"

    lines = [
        f"# {PROVENANCE}",
        f"# dryer\t{PINS['dryer']}",
        f"# crapper\t{PINS['crapper']}",
        f"# interpreter\t{sys.version.split()[0]} ({sys.platform})",
        "# threshold\t<argv, escaped>\tok:<repr of the float> | error:<message>",
    ]
    if len(set(PROBES)) != len(PROBES):
        raise SystemExit("duplicate probe")
    for probe in PROBES:
        dry = answer(lambda text: _number(text, "--threshold"), probe)
        # One shared Rust parser serves both tools only because both
        # originals are the same float(); prove it on every probe.
        if answer(_threshold, probe) != dry:
            raise SystemExit(f"crapper and dryer disagree on {probe!r}")
        lines.append(f"threshold\t{encode(probe)}\t{dry}")
    expected = ("\n".join(lines) + "\n").encode("utf-8")
    path = FIXTURES / "cases.tsv"
    if options.check:
        actual = path.read_bytes() if path.is_file() else None
        if actual != expected:
            raise SystemExit(f"Oracle differences:\n{path.relative_to(REPO)}")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(expected)
        print(f"{path.relative_to(REPO)}: {len(expected)} bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
